<#
.SYNOPSIS
    Build "VITS Studio.exe" with PyInstaller (onedir).

.DESCRIPTION
    Produces:
        dist/VITS Studio/VITS Studio.exe
        dist/VITS Studio/_internal/          <- must stay next to the exe

    onedir is used on purpose: onefile has to unpack itself on every launch
    (slow, and antivirus false positives).

    The .spec file is generated under build/ on every run so the repo never
    carries machine-specific absolute paths.

.PARAMETER Python
    Interpreter of the model environment (needs pyinstaller + pywebview).
    Defaults to $env:VITS_PYTHON.

.PARAMETER Name
    Executable / folder name. Default: "VITS Studio".

.PARAMETER Clean
    Remove dist/ and the PyInstaller work dir first.

.PARAMETER Console
    Keep a console window (useful when debugging startup crashes).

.EXAMPLE
    powershell -ExecutionPolicy Bypass -File .\build_exe.ps1

.EXAMPLE
    $env:VITS_PYTHON = 'D:\env\venv-modern\Scripts\python.exe'
    powershell -ExecutionPolicy Bypass -File .\build_exe.ps1 -Clean
#>
[CmdletBinding()]
param(
    [string]$Python = $env:VITS_PYTHON,
    [string]$Name   = 'VITS Studio',
    [switch]$Clean,
    [switch]$Console
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$RepoRoot = Split-Path -Parent $MyInvocation.MyCommand.Path
Write-Host "[build] repo root : $RepoRoot"

# ---- 0. the target exe must not be running (Windows locks it) --------------
$running = @(Get-Process -Name $Name -ErrorAction SilentlyContinue)
if ($running.Count -gt 0) {
    throw "Process '$Name' is running (PID $($running[0].Id)). Quit the app before rebuilding."
}

# ---- 1. resolve the interpreter -------------------------------------------
if (-not $Python) {
    throw "No Python given. Set `$env:VITS_PYTHON or pass -Python '<path>\python.exe'."
}
if (-not (Test-Path -LiteralPath $Python)) {
    throw "Python not found: $Python"
}
Write-Host "[build] python    : $Python"

& $Python -c "import PyInstaller, webview" 2>$null
if ($LASTEXITCODE -ne 0) {
    throw "Missing build deps in that interpreter. Run:`n  & '$Python' -m pip install pyinstaller pywebview"
}

# ---- 2. sanity check the inputs the spec will embed ------------------------
foreach ($p in @('desktop.py', 'backend\server.py', 'web\index.html')) {
    $full = Join-Path $RepoRoot $p
    if (-not (Test-Path -LiteralPath $full)) { throw "Missing required file: $full" }
}

# ---- 3. clean --------------------------------------------------------------
$BuildDir = Join-Path $RepoRoot 'build'
$DistDir  = Join-Path $RepoRoot 'dist'
$SpecPath = Join-Path $BuildDir 'VITS Studio.spec'
New-Item -ItemType Directory -Force -Path $BuildDir | Out-Null

if ($Clean) {
    Write-Host '[build] cleaning dist/ and work dir'
    Remove-Item -LiteralPath $DistDir -Recurse -Force -ErrorAction SilentlyContinue
    Remove-Item -LiteralPath (Join-Path $BuildDir $Name) -Recurse -Force -ErrorAction SilentlyContinue
    Remove-Item -LiteralPath $SpecPath -Force -ErrorAction SilentlyContinue
}

# ---- 4. generate the spec (no absolute paths inside the repo) -------------
$specText = @'
# -*- mode: python ; coding: utf-8 -*-
# GENERATED by build_exe.ps1 -- edit build_exe.ps1, not this file.
import os
from PyInstaller.utils.hooks import collect_submodules

ROOT = os.environ['VITS_REPO_ROOT']

hiddenimports = ['webview.platforms.edgechromium', 'clr']
hiddenimports += collect_submodules('webview')

datas = [
    (os.path.join(ROOT, 'backend'), 'backend'),
    (os.path.join(ROOT, 'web'), 'web'),
]

a = Analysis(
    [os.path.join(ROOT, 'desktop.py')],
    pathex=[ROOT],
    binaries=[],
    datas=datas,
    hiddenimports=hiddenimports,
    hookspath=[],
    hooksconfig={},
    runtime_hooks=[],
    excludes=[],
    noarchive=False,
    optimize=0,
)
pyz = PYZ(a.pure)

exe = EXE(
    pyz,
    a.scripts,
    [],
    exclude_binaries=True,
    name='__APP_NAME__',
    debug=False,
    bootloader_ignore_signals=False,
    strip=False,
    upx=True,
    console=__CONSOLE__,
    disable_windowed_traceback=False,
    argv_emulation=False,
    target_arch=None,
    codesign_identity=None,
    entitlements_file=None,
)
coll = COLLECT(
    exe,
    a.binaries,
    a.datas,
    strip=False,
    upx=True,
    upx_exclude=[],
    name='__APP_NAME__',
)
'@

$consoleFlag = if ($Console) { 'True' } else { 'False' }
$specText = $specText.Replace('__APP_NAME__', ($Name -replace "'", "\\'")).Replace('__CONSOLE__', $consoleFlag)
[System.IO.File]::WriteAllText($SpecPath, $specText, [System.Text.UTF8Encoding]::new($false))
Write-Host "[build] spec      : $SpecPath"

# ---- 5. run PyInstaller ----------------------------------------------------
$env:VITS_REPO_ROOT = $RepoRoot
try {
    & $Python -m PyInstaller --noconfirm --clean --distpath $DistDir --workpath $BuildDir $SpecPath
    if ($LASTEXITCODE -ne 0) { throw "PyInstaller failed with exit code $LASTEXITCODE" }
}
finally {
    Remove-Item Env:\VITS_REPO_ROOT -ErrorAction SilentlyContinue
}

# ---- 6. result -------------------------------------------------------------
$exe = Join-Path $DistDir (Join-Path $Name ($Name + '.exe'))
if (-not (Test-Path -LiteralPath $exe)) { throw "Build finished but $exe is missing." }

$sizeMb = [math]::Round(((Get-Item -LiteralPath $exe).Length / 1MB), 2)
Write-Host ''
Write-Host "[build] OK  $exe  ($sizeMb MB)"
Write-Host "[build] Note: _internal/ must stay next to the exe."
Write-Host "[build] Run needs VITS_PYTHON and VITS_MODELS (see README section 3.2)."
